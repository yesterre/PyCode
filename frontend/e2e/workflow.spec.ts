import { expect, test, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.getByLabel('账号').fill('browser-user')
  await page.getByLabel('密码').fill('browser-test-password')
  await page.getByRole('button', {name: '登录', exact: true}).click()
}

test('认证、统一异步问答、真实 Worker、SSE、历史与图谱', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', {name: '登录 PyCode'})).toBeVisible()
  await login(page)
  await expect(page.getByText('暂无项目')).toBeVisible()
  await page.getByRole('button', {name: '创建项目'}).click()
  await page.getByLabel('项目名称').fill('Browser flow')
  await page.getByLabel('仓库地址').fill('https://github.com/example/demo.git')
  await page.getByRole('button', {name: '创建项目'}).click()
  await expect(page.getByRole('heading', {name: 'Browser flow'})).toBeVisible()
  await page.getByRole('button', {name: '构建索引'}).click()
  await expect(page.getByText('索引任务已排队，正在等待 Worker。')).toBeVisible()
  await expect(page.getByText('正在索引仓库…')).toBeVisible({timeout: 10000})
  await expect(page.getByText('索引已就绪。')).toBeVisible({timeout: 20000})
  await expect(page.getByText('aaaaaaaaaaaa', {exact: true}).first()).toBeVisible()
  await expect(page.getByRole('tablist')).toHaveCount(0)

  const stream = page.waitForRequest(request => request.url().endsWith('/events'))
  await page.getByLabel('提问', {exact:true}).fill('Explain main.py')
  await page.getByLabel('分析目标（可选）', {exact:true}).fill('main.py')
  const questionRequest = page.waitForRequest(request => request.url().endsWith('/questions') && request.method() === 'POST')
  await page.getByRole('button', {name:'开始分析', exact:true}).click()
  const question = await questionRequest
  expect(question.postDataJSON()).toMatchObject({question: 'Explain main.py', target: 'main.py'})
  expect(question.postDataJSON().snapshot_id).toBeTruthy()
  expect(question.headers()['idempotency-key']).toBeTruthy()
  const live = await stream
  expect(live.headers().authorization).toMatch(/^Bearer /)
  expect(live.url()).not.toMatch(/token|Bearer/)
  await expect(page).toHaveURL(/runId=/)
  await expect(page.getByText('Controlled repository answer.', {exact:true})).toBeVisible({timeout:15000})
  await expect(page.getByText(/执行方式：快速回答/)).toBeVisible()
  await expect(page.getByLabel('持久化代码证据')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', {name:'登录 PyCode'})).toBeVisible()
  await login(page)
  await expect(page.getByText('Controlled repository answer.', {exact:true})).toBeVisible()

  await page.getByLabel('提问', {exact:true}).fill('Investigate the cross-module call chain')
  await page.getByRole('button', {name:'开始分析', exact:true}).click()
  await expect(page.getByText(/执行方式：智能体分析/)).toBeVisible()
  await expect(page.getByRole('heading', {name:'执行计划'})).toBeVisible()
  await expect(page.getByText('Controlled repository answer.', {exact:true})).toBeVisible({timeout:20000})
  await page.getByRole('textbox', {name:'提问',exact:true}).fill('Explain `unknown_symbol`')
  await page.getByRole('button', {name:'开始分析', exact:true}).click()
  await expect(page.getByText(/首轮证据不足，已升级为智能体分析/)).toBeVisible({timeout:10000})
  await expect(page.getByText('Controlled upgraded answer.', {exact:true})).toBeVisible({timeout:15000})
  await page.getByRole('button', {name:'查看历史记录'}).click()
  await expect(page.getByRole('heading', {name:'分析历史'})).toBeVisible()
  await expect(page.getByText('Where is the entry point?')).toBeVisible()
  await expect(page.getByText('The entry point is main.py.')).toBeVisible()
  await expect(page.getByText('Changes affect main.py.')).toBeVisible()
  await expect(page.getByText('Investigate the cross-module call chain')).toBeVisible()
  await page.getByRole('link', {name:'← 返回项目'}).click()
  await page.getByRole('button', {name:'打开代码图谱'}).click()
  await page.getByLabel('搜索符号或文件').fill('main')
  await page.getByRole('button', {name:'搜索图谱'}).click()
  await expect(page.getByLabel('代码图谱')).toBeVisible()
  await expect(page.getByText(/[1-9]\d* 个节点 · [1-9]\d* 条边/)).toBeVisible()
  await expect(page.getByText(/Graph Schema：4/)).toBeVisible()
  await page.getByRole('combobox', {name: '选择关系', exact: true}).selectOption('0')
  await expect(page.getByText(/Relation Type：/)).toBeVisible()
  await expect(page.getByRole('heading', {name: 'Call Site 详情'})).toBeVisible()
  const sites = page.locator('details').filter({has: page.locator('summary', {hasText: /main.py:/})})
  await sites.first().locator('summary').click()
  await expect(sites.first().getByText(/Binding Declarations：/)).toBeVisible()
  await expect(sites.first().getByText(/Flow Evidence：/)).toBeVisible()
  await page.getByRole('button', {name:'退出登录'}).click()
  await expect(page.getByRole('heading', {name:'登录 PyCode'})).toBeVisible()
  expect(errors).toEqual([])
})

test('注册、归档只读与恢复', async ({page}) => {
  const account = `new-user-${Date.now()}`
  await page.goto('/')
  await page.getByRole('button', {name: '创建账号'}).click()
  await page.getByLabel('账号', {exact: true}).fill(account)
  await page.getByLabel('密码', {exact: true}).fill('new-user-password')
  await page.getByRole('button', {name: '注册', exact: true}).click()
  await expect(page.getByText('注册成功，请登录。')).toBeVisible()
  await page.getByLabel('密码', {exact: true}).fill('new-user-password')
  await page.getByRole('button', {name: '登录', exact: true}).click()
  await expect(page.getByText('暂无项目')).toBeVisible()
  await page.getByRole('button', {name: '创建项目'}).click()
  await page.getByLabel('项目名称').fill('Lifecycle project')
  await page.getByLabel('仓库地址').fill('https://github.com/example/lifecycle.git')
  await page.getByRole('button', {name: '创建项目'}).click()
  await expect(page.getByRole('heading', {name: 'Lifecycle project'})).toBeVisible()
  await page.getByRole('link', {name: '← 返回项目'}).click()
  const archived = page.waitForResponse(response => response.url().endsWith('/archive') && response.request().method() === 'POST')
  await page.getByRole('button', {name: '归档项目', exact: true}).click()
  expect((await archived).status()).toBe(200)
  await expect(page.getByRole('heading', {name: 'Lifecycle project'})).toHaveCount(0)
  await page.getByRole('button', {name: '已归档项目'}).click()
  await expect(page.getByText('已归档 · 只读')).toBeVisible()
  await page.getByRole('heading', {name: 'Lifecycle project'}).click()
  await expect(page.getByText(/项目已归档，只读/)).toBeVisible()
  await expect(page.getByRole('button', {name: '构建索引', exact: true})).toBeDisabled()
  await page.getByLabel('提问', {exact: true}).fill('Inspect')
  await expect(page.getByRole('button', {name: '开始分析'})).toBeDisabled()
  await page.getByRole('button', {name: '查看历史记录'}).click()
  await expect(page.getByRole('heading', {name: '分析历史'})).toBeVisible()
  await page.getByRole('link', {name: '← 返回项目'}).click()
  await page.getByRole('link', {name: '← 返回项目'}).click()
  await page.getByRole('button', {name: '已归档项目'}).click()
  const restored = page.waitForResponse(response => response.url().endsWith('/restore') && response.request().method() === 'POST')
  await page.getByRole('button', {name: '恢复项目', exact: true}).click()
  expect((await restored).status()).toBe(200)
  await expect(page.getByRole('heading', {name: 'Lifecycle project'})).toHaveCount(0)
  await page.getByRole('button', {name: '正常项目'}).click()
  await page.getByRole('heading', {name: 'Lifecycle project'}).click()
  await expect(page.getByRole('button', {name: '构建索引', exact: true})).toBeEnabled()
  await page.getByRole('button', {name: '退出登录'}).click()
  await expect(page.getByRole('heading', {name: '登录 PyCode'})).toBeVisible()
})
