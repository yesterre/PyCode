import { expect, test } from '@playwright/test'

test('中文 Workspace、独立分析历史、折叠证据和受控 Agent Trace', async ({page}) => {
  await page.goto('/')
  await expect(page.getByText('暂无项目')).toBeVisible()
  await page.getByRole('button', {name: '创建项目'}).click()
  await page.getByLabel('项目名称').fill('Browser flow')
  await page.getByLabel('仓库地址').fill('https://github.com/example/demo.git')
  await page.getByRole('button', {name: '创建项目'}).click()
  await expect(page.getByRole('heading', {name: 'Browser flow'})).toBeVisible()
  await page.getByRole('button', {name: '构建索引'}).click()
  await expect(page.getByText('索引任务已排队，正在等待 Worker。')).toBeVisible()
  await expect(page.getByText('正在索引仓库…')).toBeVisible({timeout: 10000})
  await expect(page.getByText('索引已就绪。')).toBeVisible({timeout: 20000})
  await expect(page.getByText('Commit', {exact: true}).first()).toBeVisible()
  await expect(page.getByText('aaaaaaaaaaaa', {exact: true}).first()).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', {name: '查看历史记录'})).toBeVisible()
  await expect(page.getByText('Where is the entry point?')).not.toBeVisible()

  await page.getByRole('tab', {name: '智能体分析'}).click()
  await page.getByLabel('分析任务').fill('Explain the entry point')
  await page.getByRole('button', {name: '开始智能体分析'}).click()
  await expect(page).toHaveURL(/runId=/)
  await expect(page.getByText('智能体分析正在运行。')).toBeVisible({timeout: 10000})
  await expect(page.getByText('Inspect the entry point')).toBeVisible({timeout: 10000})
  await expect(page.getByText('智能体分析正在运行。')).toBeVisible()
  await expect(page.getByText('已包含证据上下文')).toBeVisible()
  await expect(page.getByText('Read main.py')).toBeVisible()
  await expect(page.getByText('Controlled analysis complete.').first()).toBeVisible({timeout: 15000})
  await page.reload()
  await expect(page.getByText('历史记录', {exact: true})).toBeVisible({timeout: 10000})
  await expect(page.getByText('Inspect the entry point')).toBeVisible()

  await page.getByRole('button', {name: '查看历史记录'}).click()
  await expect(page).toHaveURL(/\/projects\/[^/]+\/history$/)
  await expect(page.getByRole('heading', {name: '分析历史'})).toBeVisible()
  await expect(page.getByText('仓库问答', {exact: true})).toBeVisible()
  await expect(page.getByText('文件影响分析', {exact: true})).toBeVisible()
  await expect(page.getByText('智能体分析', {exact: true})).toBeVisible()
  await expect(page.getByText('Where is the entry point?')).toBeVisible()
  await expect(page.getByText('The entry point is main.py.')).toBeVisible()
  await expect(page.getByText('service.py')).toBeVisible()
  await expect(page.getByText('Changes affect main.py.')).toBeVisible()
  await expect(page.getByText('Explain the entry point')).toBeVisible()
  await expect(page.getByText('Controlled analysis complete.')).toBeVisible()

  await page.getByRole('link', {name: '← 返回项目'}).click()
  await expect(page.getByRole('heading', {name: 'Browser flow'})).toBeVisible()
  await page.getByRole('textbox', {name: '提问', exact: true}).fill('Which file starts the app?')
  await page.getByRole('button', {name: '开始分析'}).click()
  await expect(page.getByText('Controlled repository answer.')).toBeVisible({timeout: 10000})
  await expect(page.getByRole('button', {name: '展开证据'})).toBeVisible()
  await expect(page.getByText('main.py', {exact: true})).not.toBeVisible()
  await page.getByRole('button', {name: '展开证据'}).click()
  await expect(page.getByText('main.py', {exact: true})).toBeVisible()
  await page.getByRole('button', {name: '收起证据'}).click()
  await expect(page.getByText('main.py', {exact: true})).not.toBeVisible()

  await page.getByRole('button', {name: '查看历史记录'}).click()
  await expect(page.getByRole('heading', {name: '分析历史'})).toBeVisible()
  await expect(page.getByText('Which file starts the app?')).toBeVisible()
  await expect(page.getByText('Controlled repository answer.')).toBeVisible()
  await page.getByRole('link', {name: '← 返回项目'}).click()
  await expect(page.getByRole('heading', {name: 'Browser flow'})).toBeVisible()
  await page.getByRole('button', {name: '打开代码图谱'}).click()
  await page.getByLabel('搜索符号或文件').fill('main')
  await page.getByRole('button', {name: '搜索图谱'}).click()
  await expect(page.getByLabel('代码图谱')).toBeVisible()
  await expect(page.getByText(/[1-9]\d* 个节点 · [1-9]\d* 条边/)).toBeVisible()
})
