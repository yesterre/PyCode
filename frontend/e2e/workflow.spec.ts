import { expect, test } from '@playwright/test'

test('Projects through realtime Agent Trace and local Graph via Vite proxy', async ({page}) => {
  await page.goto('/')
  await expect(page.getByText('No Projects')).toBeVisible()
  await page.getByRole('button', {name: 'Create Project'}).click()
  await page.getByLabel('Project name').fill('Browser flow')
  await page.getByLabel('Repository URL').fill('https://github.com/example/demo.git')
  await page.getByRole('button', {name: 'Create Project'}).click()
  await expect(page.getByRole('heading', {name: 'Browser flow'})).toBeVisible()
  await page.getByRole('button', {name: 'Build Index'}).click()
  await expect(page.getByText('Index queued. Waiting for a worker.')).toBeVisible()
  await expect(page.getByText('Indexing repository…')).toBeVisible({timeout: 10000})
  await expect(page.getByText('Index ready.')).toBeVisible({timeout: 20000})
  await expect(page.getByText('Commit', {exact: true}).first()).toBeVisible()
  await expect(page.getByText('aaaaaaaaaaaa', {exact: true}).first()).toBeVisible()

  await page.getByRole('tab', {name: 'Agent Task'}).click()
  await page.getByLabel('Agent task').fill('Explain the entry point')
  await page.getByRole('button', {name: 'Run Agent'}).click()
  await expect(page).toHaveURL(/runId=/)
  await expect(page.getByText('Agent running.')).toBeVisible({timeout: 10000})
  // This assertion is the SSE proxy gate: plan arrives while the run remains nonterminal.
  await expect(page.getByText('Inspect the entry point')).toBeVisible({timeout: 10000})
  await expect(page.getByText('Agent running.')).toBeVisible()
  await expect(page.getByText('Evidence context included')).toBeVisible()
  await expect(page.getByText('Read main.py')).toBeVisible()
  await expect(page.getByText('Controlled analysis complete.')).toBeVisible({timeout: 15000})
  await page.reload()
  await expect(page.getByText('historical', {exact: true})).toBeVisible({timeout: 10000})
  await expect(page.getByText('Inspect the entry point')).toBeVisible()
  await page.getByRole('button', {name: 'Open Graph'}).click()
  await page.getByLabel('Search symbol or file').fill('main')
  await page.getByRole('button', {name: 'Search Graph'}).click()
  await expect(page.getByLabel('Code graph')).toBeVisible()
  await expect(page.getByText(/[1-9]\d* nodes · [1-9]\d* edges/)).toBeVisible()
})
