ROOT = Path(__file__).resolve().parents[2]
PROTOCOL = ROOT/'tests/fixtures/a07/answers.json'
PROTOCOL_SHA256 = '85a34cc455469ac642a7017264a70ff141b4b0dd2afb29d075111e2081f483d1'
WORKER = Path(__file__).with_name('a07_answer_case.py')


def sha(data):
    return hashlib.sha256(data).hexdigest()


def implementation():
    value=a07a.implementation()
    for name in ('tests/test_a07_answers.py','tests/backend/test_a07_answer_integration.py'):
        if (ROOT/name).is_file():value['files'][name]=sha((ROOT/name).read_bytes())
    return value


def export_legacy(commit, destination):
    # Git archive applies worktree conversions on Windows. Match exact Git blob
    # bytes without changing repository config or inventing a historical source.
    original=harness.git
    with patch.object(harness,'git',side_effect=lambda *args:original('-c','core.autocrlf=false',*args)):
        value=harness.export_implementation(commit,destination)
    value['representation']='git_archive_core_autocrlf_false_per_invocation'
    return value


def read_protocol(path=PROTOCOL):
    value=json.loads(Path(path).read_text(encoding='utf-8'))
    if sha(json.dumps(value,ensure_ascii=False,sort_keys=True,separators=(',',':')).encode())!=PROTOCOL_SHA256:
        raise ValueError('Fixed A07b protocol changed; version and review explicitly')
    previous,questions=a07a.read_protocol()
    if (value['a07a_protocol_sha256']!=a07a.PROTOCOL_SHA256
            or value['corpus_commit']!=questions['commit']
            or value['question_sha256']!=previous['question_sha256']):
        raise ValueError('A07a/A00 identities differ')
    return value,questions


def validate_input(directory, protocol):
    root=Path(directory).resolve()
    for name,checksum in protocol['a07a_inputs'].items():
        path=root/name
        if path.is_symlink() or not path.is_file() or sha(path.read_bytes())!=checksum:
            raise ValueError('Saved A07a artifact receipt mismatch: '+name)
    previous=json.loads((root/'results.json').read_text(encoding='utf-8'))
    if previous['question_sha256']!=protocol['question_sha256'] or previous['corpus_commit']!=protocol['corpus_commit']:
        raise ValueError('Saved A07a input identity differs')
    # Reuse only artifacts generated by the SAME production implementation.
    for name,checksum in previous['implementation']['files'].items():
        if name.startswith(('pycode/','backend/')) and sha((ROOT/name).read_bytes())!=checksum:
            raise ValueError('Production implementation changed since A07a: '+name)
    return previous


def line_pairs(calls, sources):
    result=set()
    for call in calls:
        for item in call['visible_code']:
            text=sources.get(item['path'])
            if text is None:
                raise ValueError('Model received evidence outside pinned corpus')
            lines=text.split('\n')
            for number,content in item['lines']:
                if type(number) is not int or not 1<=number<=len(lines) or lines[number-1]!=content:
                    raise ValueError('Delivered model source differs from pinned content')
                result.add((item['path'],number))
    return result


def engineering_evidence(row, truth, sources):
    # GT is available to this POST-execution observer only, never the worker/model.
    delivered=line_pairs(row['calls'],sources)
    answer_calls=[]
    for call in row['calls']:
        if call['phase']=='answer':answer_calls.append(call)
        elif call['phase']=='next_action' and call['response']:
            if json.loads(call['response']).get('action_type')=='final_answer':answer_calls.append(call)
    final=line_pairs(answer_calls[-1:],sources)
    expected={(e['path'],n) for e in truth for n in range(e['start_line'],e['end_line']+1)}
    citations=re.findall(r'(?<![\w/])([\w./-]+\.py):(\d+)(?:-(\d+))?',row['answer'] or '')
    supported=sum(all((p,n) in final for n in range(int(start),int(end or start)+1)) for p,start,end in citations)
    return dict(delivered_line_coverage=len(delivered&expected)/len(expected) if expected else None,
        answer_request_line_coverage=len(final&expected)/len(expected) if expected else None,
        source_lines_delivered=len(delivered),answer_request_source_lines=len(final),
        citation_count=len(citations),supported_citation_count=supported,
        address_support_rate=supported/len(citations) if citations else None,
        citation_grounding_scope='address_present_in_actual_answer_request_not_factual_correctness',
        unknown=not bool(truth))


def summarize(rows):
    def mean(key):
        values=[r['engineering_evidence'][key] for r in rows if r['engineering_evidence'][key] is not None]
        return sum(values)/len(values) if values else None
    count=len(rows)
    return dict(samples=count,question_ids=sorted({r['question_id'] for r in rows}),
        completion_rate=sum(r['outcome']=='complete' for r in rows)/count,
        failure_rate=sum(r['outcome']=='failed' for r in rows)/count,
        partial_rate=sum(r['outcome']=='partial' for r in rows)/count,
        runtime_ok_rate=sum(r['runtime_ok'] for r in rows)/count,
        stop_reasons=dict(Counter(r['stop_reason'] for r in rows)),
        model_calls=sum(r['model_calls'] for r in rows),model_failures=sum(r['model_failures'] for r in rows),
        model_purposes=dict(sum((Counter(c['phase'] for c in r['calls']) for r in rows),Counter())),
        tool_calls=sum(r['tool_calls'] for r in rows),tool_successes=sum(r['tool_successes'] for r in rows),
        tool_failures=sum(r['tool_failures'] for r in rows),handler_attempts=sum(r['handler_attempts'] for r in rows),
        query_embedding_calls=sum((r['execution_budget'] or {}).get('usage',{}).get('query_embeddings',0) for r in rows),
        model_input_estimated_tokens=sum(r['model_input_estimated_tokens'] for r in rows),
        output_utf8_bytes=sum(r['output_utf8_bytes'] for r in rows),
        latency_ms=harness.distribution([r['latency_ms'] for r in rows]),
        estimated_input_tokens=harness.distribution([r['model_input_estimated_tokens'] for r in rows]),
        peak_request_estimated_tokens=max(r['peak_estimated_input_tokens'] for r in rows),
        context_discard_reasons=dict(sum((Counter(d['reason_counts']) for r in rows for d in r['context_reports'] if d['delivered_to_model']),Counter())),
        delivered_line_coverage=mean('delivered_line_coverage'),answer_request_line_coverage=mean('answer_request_line_coverage'),
        citation_count=sum(r['engineering_evidence']['citation_count'] for r in rows),
        supported_citation_count=sum(r['engineering_evidence']['supported_citation_count'] for r in rows),
        unknown_samples=sum(r['engineering_evidence']['unknown'] for r in rows),
        natural_language_quality=None,billed_tokens=None,real_cost=None)


def run_benchmark(output, a07a_input, *, protocol_path=PROTOCOL):
    protocol,questions=read_protocol(protocol_path)
    output=Path(output).resolve()
    if output.exists():raise FileExistsError('Refuse to overwrite an A07b evaluation')
    previous=validate_input(a07a_input,protocol)
    before=implementation()
    corpus=a00.read_corpus(ROOT,protocol['corpus_commit']);a00.validate_dataset(questions,corpus)
    old_retriever=harness.git('show',protocol['legacy']['commit']+':pycode/retriever.py')
    if sha(old_retriever)!=protocol['legacy']['retriever_sha256']:
        raise ValueError('Substitute legacy source identity differs')
    output.mkdir(parents=True)
    (output/'execution-start.json').write_text(json.dumps(dict(implementation=before,
        protocol_sha256=PROTOCOL_SHA256,a07a_receipts=protocol['a07a_inputs'],
        started_at_utc=datetime.now(timezone.utc).isoformat()),indent=2)+'\n',encoding='utf-8')
    inputs=output/'inputs';inputs.mkdir()
    (inputs/'protocol.json').write_bytes(Path(protocol_path).read_bytes())
    (output/'questions-for-observer.json').write_bytes((ROOT/protocol['question_fixture']).read_bytes())
    public=[{k:c[k] for k in ('id','question','mode','target')} for c in questions['cases']]
    (inputs/'public-questions.json').write_text(json.dumps(public,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    a00.materialize(corpus,inputs/'corpus')
    translations={'results.json':'a07a-results.json','fixed-build/2/index.json':'index.json',
                  'fixed-build/2/graph.json':'graph.json','retrieval-131072/chunks.json':'chunks.json'}
    for name in protocol['a07a_inputs']:
        target=inputs/translations.get(name,name.replace('retrieval-131072/',''))
        target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(Path(a07a_input)/name,target)
    started=datetime.now(timezone.utc).isoformat();implementations={};rows=[]
    for family in ('legacy','current'):
        source=output/(family+'-source')
        implementations[family]=(export_legacy(protocol['legacy']['commit'],source)
            if family=='legacy' else harness.copy_current_implementation(before['head'],source))
        destination=output/(family+'-raw')
        command=[sys.executable,str(WORKER),str(source),str(inputs),str(destination),family]
        with (output/(family+'.log')).open('w',encoding='utf-8') as stream:
            child=subprocess.run(command,cwd=output,env=harness.child_environment(),stdout=stream,stderr=subprocess.STDOUT,timeout=1200)
        implementations[family]['command']=command
        implementations[family]['exit_code']=child.returncode
        if child.returncode:raise RuntimeError('Isolated worker failed; preserve '+family+'.log')
        if {p.relative_to(source).as_posix():sha(p.read_bytes()) for p in source.rglob('*') if p.is_file()}!=implementations[family]['files']:
            raise ValueError('Exported source changed during execution')
        paths=json.loads((destination/'rows.json').read_text(encoding='utf-8'))
        for path in paths:
            row=json.loads((destination/path).read_text(encoding='utf-8'))
            row['raw_result_path']=family+'-raw/'+path;rows.append(row)
    by_id={c['id']:c for c in questions['cases']}
    sources={n:b.decode('utf-8').replace('\r\n','\n').replace('\r','\n') for n,b in corpus.items()}
    for row in rows:
        case=by_id[row['question_id']]
        row['category']=case['category'];row['truth_status']=case['truth_status']
        row['engineering_evidence']=engineering_evidence(row,case['evidence'],sources)
        row['quality']={k:None for k in protocol['quality']['dimensions']}
        row['raw_result_sha256']=sha((output/row['raw_result_path']).read_bytes())
    summaries={v:summarize([r for r in rows if r['variant']==v]) for v in protocol['variants']}
    ablations={v:dict(control=protocol['variants'][v],
        baseline=summarize([r for r in rows if r['variant']=='agent' and r['question_id'] in protocol['ablation_case_ids']]),
        changed=summaries[v]) for v in protocol['variants'] if v not in {'legacy','fast','agent'}}
    if implementation()!=before:raise ValueError('Implementation changed during A07b')
    if validate_input(a07a_input,protocol)!=previous:raise ValueError('A07a evidence changed during A07b')
    # Compact observer rows refer to complete raw prompts/responses/tools on disk.
    compact=[{k:v for k,v in row.items() if k not in {'calls','tools','trace','context_reports'}} for row in rows]
    report=dict(schema_version=1,kind=protocol['kind'],protocol_sha256=PROTOCOL_SHA256,
        started_at_utc=started,finished_at_utc=datetime.now(timezone.utc).isoformat(),
        implementation=before,implementation_unchanged=True,implementations=implementations,
        corpus_commit=protocol['corpus_commit'],corpus_files={n:sha(b) for n,b in corpus.items()},
        question_sha256=protocol['question_sha256'],a07a_receipts=protocol['a07a_inputs'],
        original_A00_reproduced=False,legacy_classification=protocol['legacy']['classification'],
        environment=dict(python=platform.python_version(),platform=platform.platform(),services_used=False,
            network='blocked_in_workers',dotenv_read=False,real_models=False,
            latency_scope='preflight and execution; excludes import, artifact load, source and Memory copy'),
        current_prompt_versions=previous['prompt_versions'],parameters=protocol,
        quality_status=protocol['quality']['status'],quality=None,real_model_calls=0,real_cost=None,billed_tokens=None,
        summaries=summaries,ablations=ablations,rows=compact,
        unknown={v:summarize([r for r in rows if r['variant']==v and r['truth_status']=='unknown']) for v in protocol['variants']},
        categories={v:{c:summarize([r for r in rows if r['variant']==v and r['category']==c])
            for c in sorted({r['category'] for r in rows if r['variant']==v})} for v in protocol['variants']})
    (output/'results.json').write_text(json.dumps(report,ensure_ascii=False,indent=2,allow_nan=False)+'\n',encoding='utf-8')
    (output/'quality-protocol.json').write_text(json.dumps(protocol['quality'],ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    with (output/'human-review.csv').open('w',encoding='utf-8',newline='') as stream:
        columns=['question_id','path','truth_status','eligible_for_quality','raw_result_path','reviewer','factual_correctness',
                 'evidence_coverage','unsupported_claims','verifiable_claims','unsupported_claim_ratio','answer_completeness','source_spans','notes']
        writer=csv.DictWriter(stream,fieldnames=columns);writer.writeheader()
        for row in rows:
            if row['variant'] in {'legacy','fast','agent'} and row['repeat']==0:
                writer.writerow(dict(question_id=row['question_id'],path=row['variant'],truth_status=row['truth_status'],
                    eligible_for_quality=False,raw_result_path=row['raw_result_path'],notes='Fake engineering only; real-answer/human review scores unverified'))
    with (output/'metrics.csv').open('w',encoding='utf-8',newline='') as stream:
        columns=['question_id','variant','repeat','outcome','runtime_ok','tool_calls','tool_successes','tool_failures','model_calls',
                 'model_input_estimated_tokens','output_utf8_bytes','latency_ms','delivered_line_coverage','answer_request_line_coverage','citation_count','supported_citation_count']
        writer=csv.DictWriter(stream,fieldnames=columns,extrasaction='ignore');writer.writeheader()
        for row in rows:writer.writerow(dict(row,**row['engineering_evidence']))
    return report


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir',required=True,type=Path)
    parser.add_argument('--a07a-input',required=True,type=Path)
    args=parser.parse_args()
    report=run_benchmark(args.output_dir,args.a07a_input)
    print(json.dumps(dict(rows=len(report['rows']),quality=report['quality'],original_A00_reproduced=False,
        output=str(args.output_dir)),indent=2))


if __name__=='__main__':main()
